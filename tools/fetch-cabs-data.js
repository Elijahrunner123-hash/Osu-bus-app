#!/usr/bin/env node
// Regenerates the `routes`, `stops` and `routePatterns` literals baked into
// index.html's DATA
// section from OSU's public bus API (content.osu.edu/v2/bus). Plain Node, no
// dependencies — uses the built-in `fetch`.
//
// Usage:
//   node tools/fetch-cabs-data.js
//
// Prints the JS literals (with a generated-data header comment) to stdout.
// Paste them into index.html's DATA section, replacing the previous generated
// block. Does NOT touch index.html itself.
//
// `routePatterns` carries each route's encodedPolyline — the real road-following
// shape the buses drive — so the map can draw an actual bus path instead of a
// straight line between board and alight stops.

const ROUTES_URL = "https://content.osu.edu/v2/bus/routes";
const STOPS_URL = "https://content.osu.edu/v2/bus/stops";
const ROUTE_URL = code => `https://content.osu.edu/v2/bus/routes/${code}`;

function jsString(s) {
  return JSON.stringify(s);
}

async function main() {
  const [routesRes, stopsRes] = await Promise.all([
    fetch(ROUTES_URL),
    fetch(STOPS_URL),
  ]);
  if (!routesRes.ok) throw new Error(`routes fetch failed: ${routesRes.status}`);
  if (!stopsRes.ok) throw new Error(`stops fetch failed: ${stopsRes.status}`);

  const routesJson = await routesRes.json();
  const stopsJson = await stopsRes.json();

  const routes = routesJson.data.routes.map(r => ({
    code: r.code,
    name: r.name,
    color: r.color,
    darkColor: r.darkColor,
  }));

  const stops = stopsJson.data.stops.map(s => ({
    id: s.id,
    name: s.name,
    lat: s.latitude,
    lng: s.longitude,
    routes: s.routes.map(r => r.code),
  }));

  // Per-route detail: the ordered stop sequence and the road-following shapes.
  // One request per route; a handful of routes, run rarely, so no throttling needed.
  const detail = {};
  for (const r of routes) {
    const res = await fetch(ROUTE_URL(r.code));
    if (!res.ok) throw new Error(`route ${r.code} fetch failed: ${res.status}`);
    const json = await res.json();
    detail[r.code] = {
      patterns: (json.data.patterns || [])
        .filter(p => p.encodedPolyline)
        .map(p => ({ id: String(p.id), direction: p.direction, polyline: p.encodedPolyline })),
    };
  }

  // Use the later of the two lastModified timestamps for the generated-data comment.
  const lastModified = [routesJson.lastModified, stopsJson.lastModified].sort().pop();

  const header = `// Generated by tools/fetch-cabs-data.js from OSU's public bus API
// (content.osu.edu/v2/bus/routes, content.osu.edu/v2/bus/stops).
// Regenerate with: node tools/fetch-cabs-data.js
// Source lastModified: ${lastModified}
// Stop count: ${stops.length}`;

  console.log(header);
  console.log();
  console.log("const routes = [");
  for (const r of routes) {
    console.log(`  { code: ${jsString(r.code)}, name: ${jsString(r.name)}, color: ${jsString(r.color)}, darkColor: ${jsString(r.darkColor)} },`);
  }
  console.log("];");
  console.log();
  console.log("const stops = [");
  for (const s of stops) {
    console.log(`  { id: ${jsString(s.id)}, name: ${jsString(s.name)}, lat: ${s.lat}, lng: ${s.lng}, routes: [${s.routes.map(jsString).join(", ")}] },`);
  }
  console.log("];");
  console.log();
  console.log("// Google-encoded polylines of the real road-following route shapes.");
  console.log("const routePatterns = {");
  for (const r of routes) {
    const ps = detail[r.code].patterns;
    console.log(`  ${r.code}: [`);
    for (const p of ps) {
      console.log(`    { id: ${jsString(p.id)}, direction: ${jsString(p.direction)}, polyline: ${jsString(p.polyline)} },`);
    }
    console.log("  ],");
  }
  console.log("};");
}

main().catch(err => {
  console.error("fetch-cabs-data failed:", err.message);
  process.exit(1);
});
